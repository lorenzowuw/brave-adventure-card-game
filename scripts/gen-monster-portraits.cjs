function bg(areaId) {
  const a = AREA[areaId];
  const verticals = Array.from({ length: 9 }, (_, i) => {
    const x = 70 + i * 185 + (i % 2) * 52;
    const w = 28 + (i % 3) * 18;
    return `<rect x="${x}" y="0" width="${w}" height="804" fill="#030903" opacity="0.48"/>
      <rect x="${x + w + 10}" y="0" width="${Math.max(18, w - 8)}" height="804" fill="${a.stripe}" opacity="0.32"/>`;
  }).join('');
  const diagonals = Array.from({ length: 15 }, (_, i) => {
    const x = -220 + i * 150;
    return `<path d="M${x} 934 L${x + 270} 804" stroke="${a.band}" stroke-width="42" opacity="0.34"/>`;
  }).join('');
  return `<rect width="${W}" height="${H}" fill="${a.bg}"/>
    ${verticals}
    <rect x="0" y="804" width="${W}" height="140" fill="${a.floor}" opacity="0.72"/>
    <rect x="0" y="804" width="${W}" height="140" fill="url(#floorFade)" opacity="0.6"/>
    ${diagonals}`;
}

